def spanish(name: str) -> str:
    """Spanish name for an English spell name, or raise when uncurated."""
    direct = BASE.get(name)
    if direct:
        return direct

    for suffix, spanish_suffix in SUFFIXES:
        if name.endswith(suffix):
            return spanish(name[: -len(suffix)]) + spanish_suffix

    for prefix, build in COMPOSERS:
        if name.startswith(prefix):
            return build(spanish(name[len(prefix):]))

    for stem, spanish_stem in SERIES.items():
        if name.startswith(stem + " ") and name[len(stem) + 1:] in ROMAN:
            return f"{spanish_stem} {name[len(stem) + 1:]}"

    for prefix, spanish_prefix in PATTERNS.items():
        if name.startswith(prefix):
            tail = TAIL.get(name[len(prefix):])
            if tail:
                return spanish_prefix + tail

    raise KeyError(name)
